// Helper to find district by name or ID (case-insensitive, hindi/english)
export function findDistrictHyperlocal(query) {
  if (!query) return mpDistrictsHyperlocal[0];
  const q = query.trim().toLowerCase();
  return (
    mpDistrictsHyperlocal.find(
      d =>
        d.id.toLowerCase() === q ||
        d.name.toLowerCase() === q ||
        d.nameHi.includes(query) ||
        d.name.toLowerCase().includes(q)
    ) || mpDistrictsHyperlocal[0]
  );
}
